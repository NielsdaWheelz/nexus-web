"""Write, or with ``--check`` verify, the browser's tool projection revision.

Run from ``python/``: ``uv run python scripts/generate_tool_contract_projection.py``.
"""

import argparse
from pathlib import Path

from nexus.services.tools.contract import PROJECTION_REVISION

PATH = Path(__file__).resolve().parents[2] / "apps/web/src/lib/chat/toolContractProjection.ts"
CONTENT = f"""// @generated by python/scripts/generate_tool_contract_projection.py; do not edit.
export const TOOL_PROJECTION_REVISION = "{PROJECTION_REVISION}" as const;
"""

if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    if not parser.parse_args().check:
        PATH.write_text(CONTENT)
    elif PATH.read_text() != CONTENT:
        raise SystemExit(f"{PATH} is stale; run scripts/generate_tool_contract_projection.py")
