"""Write the web's copy of the capability columns it reads.

Source: ``CAPABILITIES`` in ``nexus/services/resource_items/capabilities.py`` and
``CONNECTION_DISCOVERY_SOURCE_SCHEMES`` in ``nexus/services/resource_graph/edges.py``.
Output: ``apps/web/src/lib/resources/resourceCapabilities.ts``. Run after changing either:

    make generate-resource-capabilities
"""

from __future__ import annotations

import json
from pathlib import Path

from nexus.services.resource_graph.edges import CONNECTION_DISCOVERY_SOURCE_SCHEMES
from nexus.services.resource_items.capabilities import CAPABILITIES, InspectorPolicy

OUTPUT = Path(__file__).resolve().parents[2] / "apps/web/src/lib/resources/resourceCapabilities.ts"

_HEADER = """// @generated by python/scripts/generate_resource_capabilities.py from CAPABILITIES
// (python/nexus/services/resource_items/capabilities.py); do not edit by hand.
import type { ResourceScheme } from "@/lib/resourceGraph/resourceRef";
import type { ShareMode } from "@/lib/sharing/types";

export type ResourceInspectorSurfaceRole =
  "Contents" | "LinkedItems" | "Forks";
export type ResourceInspectorLinkedItemsSurface =
  "MediaEvidence" | "ResourceConnections";

/** `default_surface_order` is fallback preference, not tab order. */
export interface ResourceInspectorResourcePolicy {
  readonly linked_items: ResourceInspectorLinkedItemsSurface;
  readonly forks: "ConversationForks" | null;
  readonly default_surface_order: readonly ResourceInspectorSurfaceRole[];
}

interface ResourceCapability {
  readonly link_mode: "none" | "direct" | "materialize_passage";
  readonly sharing: ShareMode;
  readonly app_search_scope: boolean;
  readonly inspector: ResourceInspectorResourcePolicy | null;
}
"""

_FOOTER = """
export function resourceSchemeIsAppSearchScope(
  scheme: ResourceScheme,
): boolean {
  return RESOURCE_CAPABILITIES[scheme].app_search_scope;
}
"""


def _inspector(policy: InspectorPolicy | None) -> list[str]:
    if policy is None:
        return ["    inspector: null,"]
    order = ", ".join(json.dumps(role) for role in policy.default_surface_order)
    return [
        "    inspector: {",
        f"      linked_items: {json.dumps(policy.linked_items)},",
        f"      forks: {json.dumps(policy.forks)},",
        f"      default_surface_order: [{order}],",
        "    },",
    ]


def render() -> str:
    lines = ["export const RESOURCE_CAPABILITIES = {"]
    for scheme, row in CAPABILITIES.items():
        lines += [
            f"  {scheme}: {{",
            f"    link_mode: {json.dumps(row.link_mode)},",
            f"    sharing: {json.dumps(row.sharing)},",
            f"    app_search_scope: {json.dumps(row.app_search_scope)},",
            *_inspector(row.inspector),
            "  },",
        ]
    lines.append("} as const satisfies Record<ResourceScheme, ResourceCapability>;")
    lines += ["", "export const CONNECTION_DISCOVERY_SOURCE_SCHEMES = ["]
    lines += [f"  {json.dumps(scheme)}," for scheme in CONNECTION_DISCOVERY_SOURCE_SCHEMES]
    lines.append("] as const satisfies readonly ResourceScheme[];")
    return _HEADER + "\n" + "\n".join(lines) + "\n" + _FOOTER


if __name__ == "__main__":
    OUTPUT.write_text(render(), encoding="utf-8")
    print(f"wrote {OUTPUT}")
