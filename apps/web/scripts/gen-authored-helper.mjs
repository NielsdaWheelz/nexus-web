// Bundles the shared semantic kernel for the Python transaction owner.
// An optional output path lets the static gate check freshness without edits.
import { execFileSync } from "node:child_process";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const webDir = join(dirname(fileURLToPath(import.meta.url)), "..");
const output = process.argv[2] === undefined
  ? join(webDir, "../../node/authored/helper.mjs")
  : resolve(process.argv[2]);
execFileSync("bun", [
  "build", "../../node/authored/helper.ts", "--target=node", "--format=esm", "--minify",
  "--banner=// generated by apps/web/scripts/gen-authored-helper.mjs; do not edit.",
  `--outfile=${output}`,
], { cwd: webDir, stdio: ["ignore", "ignore", "inherit"] });
