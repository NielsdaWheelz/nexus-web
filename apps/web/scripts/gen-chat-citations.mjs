// Bundles the renderer's citation grammar for the Python publication owner.
// An optional output path lets the static gate check freshness without edits.
import { execFileSync } from "node:child_process";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const webDir = join(dirname(fileURLToPath(import.meta.url)), "..");
const output = process.argv[2] === undefined
  ? join(webDir, "../../python/nexus/services/chat/markdown_citations.mjs")
  : resolve(process.argv[2]);
execFileSync("bun", [
  "build", "scripts/chatCitationMarkers.ts", "--target=node", "--format=esm", "--minify",
  "--banner=// generated by apps/web/scripts/gen-chat-citations.mjs; do not edit.",
  `--outfile=${output}`,
], { cwd: webDir, stdio: ["ignore", "ignore", "inherit"] });
